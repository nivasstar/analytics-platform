# FORECASTS VS FACTS
# ============================================================

def render_forecasts_vs_facts(
    report,
    dataframe,
):
    df = dataframe.copy()

    if "forecast_type" not in df.columns:
        df["forecast_type"] = "forecast"

    df["forecast_type"] = (
        df["forecast_type"]
        .fillna("forecast")
    )

    # --------------------------------------------------------
    # Point forecasts
    # --------------------------------------------------------
    point = df[
        (df["forecast_operator"] == "eq")
        & df["percentage_error"].notna()
    ].copy()

    point["abs_percentage_error"] = (
        point["percentage_error"].abs()
    )

    closest = point.nsmallest(
        5,
        "abs_percentage_error",
    )

    biggest = point.nlargest(
        5,
        "abs_percentage_error",
    )

    # --------------------------------------------------------
    # Horizon buckets
    # --------------------------------------------------------
    def horizon_bucket(years):
        if years != years:
            return "Unknown"

        if years < 1:
            return "< 1 year"

        if years < 3:
            return "1–3 years"

        if years < 10:
            return "3–10 years"

        return "10+ years"

    point["horizon_bucket"] = (
        point["forecast_horizon_years"]
        .apply(horizon_bucket)
    )

    horizon_accuracy = (
        point
        .groupby("horizon_bucket")
        .agg(
            forecasts=(
                "forecast_id",
                "count",
            ),
            mean_abs_error=(
                "abs_percentage_error",
                "mean",
            ),
            median_abs_error=(
                "abs_percentage_error",
                "median",
            ),
        )
        .reset_index()
    )

    type_accuracy = (
        point
        .groupby("forecast_type")
        .agg(
            forecasts=(
                "forecast_id",
                "count",
            ),
            mean_abs_error=(
                "abs_percentage_error",
                "mean",
            ),
            median_abs_error=(
                "abs_percentage_error",
                "median",
            ),
        )
        .reset_index()
    )

    # --------------------------------------------------------
    # Helpers
    # --------------------------------------------------------
    def format_date(value):
        if value != value:
            return "N/A"

        try:
            return value.date()
        except AttributeError:
            return value

    def format_number(value):
        if value != value:
            return "N/A"

        return f"{value:.2f}"

    def ranking_table(data):
        rows = []

        for _, row in data.iterrows():
            rows.append(
                f'| {row["topic"]} '
                f'| {row["forecast_type"]} '
                f'| {format_date(row["forecast_date"])} '
                f'| {format_date(row["target_date"])} '
                f'| {row["forecast_horizon"]} '
                f'| {format_number(row["forecast_value"])} '
                f'| {format_number(row["actual_value"])} '
                f'| {row["abs_percentage_error"]:.2f}% |'
            )

        return "\n".join(rows)

    closest_rows = ranking_table(
        closest
    )

    biggest_rows = ranking_table(
        biggest
    )

    # --------------------------------------------------------
    # Horizon accuracy table
    # --------------------------------------------------------
    horizon_rows = []

    for _, row in horizon_accuracy.iterrows():
        horizon_rows.append(
            f'| {row["horizon_bucket"]} '
            f'| {int(row["forecasts"])} '
            f'| {row["mean_abs_error"]:.2f}% '
            f'| {row["median_abs_error"]:.2f}% |'
        )

    horizon_rows = "\n".join(
        horizon_rows
    )

    # --------------------------------------------------------
    # Forecast type accuracy table
    # --------------------------------------------------------
    type_rows = []

    for _, row in type_accuracy.iterrows():
        type_rows.append(
            f'| {row["forecast_type"]} '
            f'| {int(row["forecasts"])} '
            f'| {row["mean_abs_error"]:.2f}% '
            f'| {row["median_abs_error"]:.2f}% |'
        )

    type_rows = "\n".join(
        type_rows
    )

    # --------------------------------------------------------
    # Complete comparison table
    # --------------------------------------------------------
    comparison_rows = []

    for _, row in df.iterrows():
        error = (
            f'{row["percentage_error"]:.2f}%'
            if row["percentage_error"]
            == row["percentage_error"]
            else "N/A"
        )

        operator = row.get(
            "forecast_operator",
            "eq",
        )

        forecast_display = format_number(
            row.get("forecast_value")
        )

        if operator == "range":
            lower = row.get(
                "forecast_lower"
            )

            upper = row.get(
                "forecast_upper"
            )

            if (
                lower == lower
                and upper == upper
            ):
                forecast_display = (
                    f"{lower:.2f}–{upper:.2f}"
                )

        elif operator == "gt":
            forecast_display = (
                f"> {forecast_display}"
            )

        elif operator == "lt":
            forecast_display = (
                f"< {forecast_display}"
            )

        comparison_rows.append(
            f'| {row["category"]} '
            f'| {row["forecast_type"]} '
            f'| {row["topic"]} '
            f'| {format_date(row["forecast_date"])} '
            f'| {format_date(row["target_date"])} '
            f'| {row["forecast_horizon"]} '
            f'| {forecast_display} '
            f'| {format_number(row["actual_value"])} '
            f'| {error} '
            f'| {row["outcome_classification"]} |'
        )

    comparison_rows = "\n".join(
        comparison_rows
    )

    forecast_types = (
        df["forecast_type"]
        .value_counts()
        .to_dict()
    )

    type_summary = "\n".join(
        f"- {name}: {count}"
        for name, count
        in forecast_types.items()
    )

    # --------------------------------------------------------
    # Generate visuals
    # --------------------------------------------------------
    charts = (
        build_forecasts_vs_facts_charts(
            df
        )
    )

    scatter_chart = (
        f'![Forecast vs Actual]({charts["scatter"]})'
        if charts["scatter"]
        else "Not enough data."
    )

    error_chart = (
        f'![Largest Forecast Errors]({charts["errors"]})'
        if charts["errors"]
        else "Not enough data."
    )

    horizon_chart = (
        f'![Accuracy by Horizon]({charts["horizon"]})'
        if charts["horizon"]
        else "Not enough data."
    )

    return f"""# {report["name"]}

{report.get("description", "")}

## Summary

- Total comparisons: {len(df)}
- Quantitative point forecasts: {len(point)}
- Categories: {df["category"].nunique()}

### Forecast Types

{type_summary}

## Forecast vs Actual

{scatter_chart}

Points closer to the diagonal represent forecasts that were closer
to the observed outcome.

## Largest Forecast Errors

{error_chart}

## Accuracy by Forecast Horizon

{horizon_chart}

| Horizon | Forecasts | Mean Absolute Error | Median Absolute Error |
|---|---:|---:|---:|
{horizon_rows}

## Closest Forecasts

| Topic | Type | Forecast Made | Target | Horizon | Forecast | Actual | Absolute Error % |
|---|---|---|---|---|---:|---:|---:|
{closest_rows}

## Biggest Misses

| Topic | Type | Forecast Made | Target | Horizon | Forecast | Actual | Absolute Error % |
|---|---|---|---|---|---:|---:|---:|
{biggest_rows}

## Accuracy by Forecast Type

| Forecast Type | Forecasts | Mean Absolute Error | Median Absolute Error |
|---|---:|---:|---:|
{type_rows}

## All Forecasts vs Facts

| Category | Type | Topic | Forecast Made | Target | Horizon | Forecast | Actual | Error % | Classification |
|---|---|---|---|---|---|---:|---:|---:|---|
{comparison_rows}

---
Generated by Analytics Platform
"""


