# ECONOMIC HISTORY
# ============================================================

def render_economic_history(report, dataframe):
    country = dataframe.iloc[0]["country"]

    useful = dataframe[
        dataframe[
            [
                "population",
                "gdp",
                "gdp_per_capita",
            ]
        ].notna().any(axis=1)
    ].copy()

    milestone_years = [
        -1000,
        1,
        1000,
        1500,
        1700,
        1800,
        1900,
        1950,
        1960,
        2000,
        2020,
        2025,
    ]

    selected = useful[
        useful["year"].isin(
            milestone_years
        )
    ]

    rows = []

    for _, row in selected.iterrows():
        population = (
            f'{row["population"]:,.0f}'
            if row["population"] == row["population"]
            else "N/A"
        )

        gdp = (
            f'{row["gdp"]:,.0f}'
            if row["gdp"] == row["gdp"]
            else "N/A"
        )

        gdppc = (
            f'{row["gdp_per_capita"]:,.2f}'
            if row["gdp_per_capita"]
            == row["gdp_per_capita"]
            else "N/A"
        )

        rows.append(
            f'| {int(row["year"])} '
            f'| {population} '
            f'| {gdp} '
            f'| {gdppc} |'
        )

    table_rows = "\n".join(rows)

    charts = build_economic_history_charts(
        dataframe,
        country,
    )

    population_chart = (
        f'![Population History]({charts["population"]})'
        if charts["population"]
        else "Not enough population data."
    )

    gdppc_chart = (
        f'![GDP per Capita History]({charts["gdp_per_capita"]})'
        if charts["gdp_per_capita"]
        else "Not enough GDP-per-capita data."
    )

    return f"""# {report["name"]}

{report.get("description", "")}

## {country}

## Population Through History

{population_chart}

## GDP per Capita Through History

{gdppc_chart}

## Historical Milestones

| Year | Population | GDP | GDP per Capita |
|---:|---:|---:|---:|
{table_rows}

## Coverage

- Earliest year: {int(dataframe["year"].min())}
- Latest year: {int(dataframe["year"].max())}
- Canonical observations: {len(dataframe)}
- Duplicate years: {dataframe["year"].duplicated().sum()}

---
Generated by Analytics Platform
"""


