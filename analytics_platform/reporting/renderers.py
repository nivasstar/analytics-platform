# DECISIONS VS OUTCOMES
# ============================================================

def render_decisions_vs_outcomes(
    report,
    dataframe,
):
    df = dataframe.copy()

    rows = []

    for _, row in df.iterrows():
        decision_date = (
            row["decision_date"].date()
            if row["decision_date"]
            == row["decision_date"]
            else "N/A"
        )

        outcome_date = (
            row["outcome_date"].date()
            if row["outcome_date"]
            == row["outcome_date"]
            else "N/A"
        )

        horizon = (
            f'{row["outcome_horizon_years"]:.1f} years'
            if row.get(
                "outcome_horizon_years"
            )
            == row.get(
                "outcome_horizon_years"
            )
            else "N/A"
        )

        predicted = row.get(
            "claim_at_time",
            "N/A",
        )

        outcome = (
            f'{row["outcome_value"]:.2f} '
            f'{row.get("outcome_unit", "")}'
            if row["outcome_value"]
            == row["outcome_value"]
            else "N/A"
        )

        rows.append(
            f'| {row["category"]} '
            f'| {row["decision"]} '
            f'| {decision_date} '
            f'| {outcome_date} '
            f'| {horizon} '
            f'| {predicted} '
            f'| {outcome} '
            f'| {row["confidence"]} |'
        )

    table_rows = "\n".join(rows)

    charts = (
        build_decisions_vs_outcomes_charts(
            df
        )
    )

    comparison_chart = (
        f'![Prediction vs Outcome]({charts["comparison"]})'
        if charts["comparison"]
        else "Not enough comparable numeric data."
    )

    horizon_chart = (
        f'![Decision Horizons]({charts["horizon"]})'
        if charts["horizon"]
        else "Not enough horizon data."
    )

    return f"""# {report["name"]}

{report.get("description", "")}

## Summary

- Decisions analyzed: {len(df)}
- Categories: {df["category"].nunique()}
- Jurisdictions: {df["jurisdiction"].nunique()}

## Published Expectations vs Outcomes

{comparison_chart}

## Decision-to-Outcome Horizon

{horizon_chart}

## Decisions vs Outcomes

| Category | Decision | Decision Date | Outcome Date | Horizon | Claim at the Time | Observed Outcome | Confidence |
|---|---|---|---|---|---|---|---|
{table_rows}

## Interpretation Principle

Observed outcomes are reported separately from causal attribution.

A change occurring after a policy decision does not, by itself,
prove that the policy caused the entire observed effect.

---
Generated by Analytics Platform
"""


# ============================================================
# RENDERER REGISTRY
# ============================================================

RENDERERS = {
    "market_risk": render_market_risk,
    "economic_history": render_economic_history,
    "forecasts_vs_facts": render_forecasts_vs_facts,
    "decisions_vs_outcomes": render_decisions_vs_outcomes,
    "generic": render_generic,
}


def get_renderer(name):
    if name not in RENDERERS:
        raise ValueError(
            f"Unknown renderer: {name}"
        )

    return RENDERERS[name]
